"""Hospital system world (branch hospital-system): corridor, pharmacy, 4 patient rooms.

    ros2 launch robot_gazebo hospital_system.launch.py gui:=false            # headless (tests)
    ros2 launch robot_gazebo hospital_system.launch.py gui:=false video:=true  # overview cam 2 Hz
    ros2 launch robot_gazebo hospital_system.launch.py gui:=false photo:=true  # + report cameras

Same robot and the same helpers as hospital.launch.py (ogre renderer, planar base
~/sdp_sim/scripts/planar_base.py, controllers), plus everything the system has once per
room / container, read from ~/sdp_sim/config/hospital_map.yaml (generated by
tools/make_system_world.py):
  - robot from urdf/jetarm_mecanum_system.gazebo.xacro (one DetachableJoint per container)
  - bridge: /med_<slot>/attach|detach (std_msgs/Empty ->), /med_<slot>/attached (<- String),
    /smart_table_N/contact, /smart_table_N/joint_states (<-), /smart_table_N/liftK/cmd_pos (->)
  - ONE smart-table controller for all tables: smart_table.py --map ...
The containers themselves are spawned after start-up by ~/sdp_sim/scripts/pharmacy.py
setup (their welds form when they first appear and are released right away).
"""
import os

import yaml
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, ExecuteProcess, IncludeLaunchDescription, RegisterEventHandler
from launch.event_handlers import OnProcessExit
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import Command, LaunchConfiguration, PythonExpression
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue

SDP = os.path.expanduser('~/sdp_sim')
MAP = os.path.join(SDP, 'config', 'hospital_map.yaml')


def generate_launch_description():
    pkg = get_package_share_directory('robot_gazebo')
    with open(MAP) as fh:
        m = yaml.safe_load(fh)
    containers = list(m['pharmacy']['containers'].values())
    prefixes = [t['prefix'] for _, t in sorted(m['tables'].items())]

    world = PythonExpression(["'", os.path.join(pkg, 'worlds', 'hospital_system'), "' + ('_video' if '",
                              LaunchConfiguration('video'), "'.lower() == 'true' else ('_photo' if '",
                              LaunchConfiguration('photo'), "'.lower() == 'true' else '')) + '.sdf'"])
    xacro_file = os.path.join(pkg, 'urdf', 'jetarm_mecanum_system.gazebo.xacro')

    gazebo = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(
            get_package_share_directory('ros_ign_gazebo'), 'launch', 'ign_gazebo.launch.py')),
        launch_arguments=[('ign_args', PythonExpression([
            "' -r ' + ('' if '", LaunchConfiguration('gui'), "'.lower() == 'true' else '-s ') + ",
            "'--render-engine ogre ' + '", world, "'"]))])

    bridge = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(pkg, 'launch', 'ros_ign_bridge.launch.py')),
        launch_arguments={'use_sim_time': 'true'}.items())

    robot_state_publisher = Node(
        package='robot_state_publisher', executable='robot_state_publisher', output='screen',
        parameters=[{'robot_description': ParameterValue(Command(['xacro ', xacro_file]), value_type=str),
                     'use_sim_time': True}])

    spawn = Node(
        package='ros_ign_gazebo', executable='create', output='screen',
        arguments=['-topic', 'robot_description', '-name', 'robot', '-x', '0', '-y', '0', '-z', '0'],
        parameters=[{'use_sim_time': True}])

    args = ['/base/vel_x@std_msgs/msg/Float64]ignition.msgs.Double',
            '/base/vel_y@std_msgs/msg/Float64]ignition.msgs.Double',
            '/base/vel_yaw@std_msgs/msg/Float64]ignition.msgs.Double',
            '/overview_cam/image@sensor_msgs/msg/Image[ignition.msgs.Image']
    for c in containers:
        args += ['/%s/attach@std_msgs/msg/Empty]ignition.msgs.Empty' % c,
                 '/%s/detach@std_msgs/msg/Empty]ignition.msgs.Empty' % c,
                 '/%s/attached@std_msgs/msg/String[ignition.msgs.StringMsg' % c]
    for p in prefixes:
        args += ['%s/contact@ros_gz_interfaces/msg/Contacts[ignition.msgs.Contacts' % p,
                 '%s/joint_states@sensor_msgs/msg/JointState[ignition.msgs.Model' % p]
        args += ['%s/lift%d/cmd_pos@std_msgs/msg/Float64]ignition.msgs.Double' % (p, i) for i in range(1, 4)]
    args += ['/room_cam/%s/image@sensor_msgs/msg/Image[ignition.msgs.Image' % k for k in 'abcd']
    base_bridge = Node(package='ros_gz_bridge', executable='parameter_bridge', name='base_bridge',
                       output='screen', arguments=args)

    planar_base = ExecuteProcess(cmd=['python3', os.path.join(SDP, 'scripts', 'planar_base.py')], output='screen')
    smart_tables = ExecuteProcess(cmd=['python3', os.path.join(SDP, 'scripts', 'smart_table.py'), '--map', MAP],
                                  output='screen')

    def spawner(name):
        return Node(package='controller_manager', executable='spawner', arguments=[name], output='screen')

    jsb, arm, grip = spawner('joint_state_broadcaster'), spawner('arm_controller'), spawner('gripper_controller')

    return LaunchDescription([
        DeclareLaunchArgument('gui', default_value='true', description='false = headless Gazebo server'),
        DeclareLaunchArgument('video', default_value='false', description='true = overview camera at 2 Hz'),
        DeclareLaunchArgument('photo', default_value='false', description='true = + report cameras /room_cam/*'),
        gazebo, bridge, base_bridge, planar_base, smart_tables, robot_state_publisher, spawn,
        RegisterEventHandler(OnProcessExit(target_action=spawn, on_exit=[jsb])),
        RegisterEventHandler(OnProcessExit(target_action=jsb, on_exit=[arm])),
        RegisterEventHandler(OnProcessExit(target_action=arm, on_exit=[grip])),
    ])

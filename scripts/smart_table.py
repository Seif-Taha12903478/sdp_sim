class TableMonitor:
    """Follows the table node's topics inside another node (mission.py, CLI, tests).
    sim_t comes from /joint_states stamps, like medicine_weld.Weld."""

    def __init__(self, node, prefix='/smart_table'):
        self.node, self.prefix = node, prefix
        self.states = []            # (sim_t, state) on every change
        self.contacts = []          # (sim_t, contact_state) on every change
        self.height = None
        self.sim_t = None
        self.on_contact = None      # optional callback(contact_state, sim_t)
        node.create_subscription(String, prefix + '/state', self._on_state, latched_qos())
        node.create_subscription(String, prefix + '/contact_state', self._on_contact, latched_qos())
        node.create_subscription(Float64, prefix + '/height', self._on_height, 10)
        node.create_subscription(JointState, '/joint_states', self._on_js, 1)

    def _on_js(self, m):
        t = stamp_s(m.header)
        if self.sim_t is None or t > self.sim_t:
            self.sim_t = t

    def _on_state(self, m):
        if not self.states or self.states[-1][1] != m.data:
            self.states.append((self.sim_t, m.data))

    def _on_contact(self, m):
        if not self.contacts or self.contacts[-1][1] != m.data:
            self.contacts.append((self.sim_t, m.data))
            if self.on_contact:
                self.on_contact(m.data, self.sim_t)

    def _on_height(self, m):
        self.height = m.data

    def state(self):
        return self.states[-1][1] if self.states else None

    def contact(self):
        return self.contacts[-1][1] if self.contacts else None

    def spin_until(self, cond, sim_seconds, wall_limit=3600.0, every=None):
        """Spin until cond() or sim_seconds of sim time have passed. every=(sim_s, fn)
        calls fn() periodically (progress logs)."""
        w_end = time.monotonic() + wall_limit
        while self.sim_t is None and time.monotonic() < w_end:
            rclpy.spin_once(self.node, timeout_sec=0.2)
        if self.sim_t is None:
            return cond()
        t_end, t_next = self.sim_t + sim_seconds, None
        while self.sim_t < t_end and time.monotonic() < w_end:
            if cond():
                return True
            if every:
                if t_next is None or self.sim_t >= t_next:
                    t_next = self.sim_t + every[0]
                    every[1]()
            rclpy.spin_once(self.node, timeout_sec=0.2)
        return cond()

    def wait_state(self, want, sim_seconds, **kw):
        return self.spin_until(lambda: self.state() == want, sim_seconds, **kw)


def cli(cmd, prefix='/smart_table'):
    rclpy.init()
    node = rclpy.create_node('smart_table_cli')
    mon = TableMonitor(node, prefix)
    code = 0
    try:
        mon.spin_until(lambda: mon.state() is not None and mon.height is not None, 10.0, wall_limit=60.0)
        if cmd in ('raise', 'lower'):
            cl = node.create_client(Trigger, prefix + '/' + cmd)
            if not cl.wait_for_service(timeout_sec=60.0):
                sys.exit('%s/%s not available - is the table node running?' % (prefix, cmd))
            fut = cl.call_async(Trigger.Request())
            rclpy.spin_until_future_complete(node, fut, timeout_sec=120.0)
            r = fut.result()
            print('%s: %s' % (cmd, r.message if r else 'no answer'))
            if not r or not r.success:
                code = 2
            else:
                want = 'raised' if cmd == 'raise' else 'lowered'
                ok = mon.wait_state(want, 60.0, every=(2.0, lambda: print('  %s  platform %.3f m'
                                                                          % (mon.state(), mon.height or 0))))
                print('%s: %s, platform %.3f m' % (want, 'yes' if ok else 'NO (timeout)', mon.height or 0))
                code = 0 if ok else 3
        print('state %s, platform top %s m, container contact %s'
              % (mon.state(), '%.3f' % mon.height if mon.height is not None else '?', mon.contact()))
    finally:
        node.destroy_node()
        rclpy.shutdown()
    sys.exit(code)


def main():
    import argparse
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('cmd', nargs='?', choices=['raise', 'lower', 'status'], help='manual command (CLI)')
    p.add_argument('--prefix', default='/smart_table', help='CLI: table topic prefix, e.g. /smart_table_3')
    p.add_argument('--map', default=None, help='hospital system: run the controller for every table in '
                                               'this map (config/hospital_map.yaml)')
    a = p.parse_args()
    if a.cmd:
        cli(a.cmd, a.prefix)
    rclpy.init()
    node = SmartTableNode(*system_tables(a.map)) if a.map else SmartTableNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == '__main__':
    main()
